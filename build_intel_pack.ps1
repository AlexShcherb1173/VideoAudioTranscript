# ======================================================================
# INTEL DRIVER PACK DOWNLOADER + EXTRACTOR + ZIP PACKER
# ======================================================================
#
# Что делает данный PowerShell-скрипт:
#
# Скрипт автоматически:
# 1. Создаёт рабочие папки на диске C:
# 2. Скачивает набор Intel-драйверов по прямым ссылкам
# 3. Пытается распаковать каждый скачанный установщик в отдельную папку
# 4. Удаляет .exe-файлы после распаковки
# 5. Упаковывает итоговую структуру в ZIP-архив
#
# В результате получается готовый архив:
# C:\IntelPack_AlderLake.zip
#
# Основной сценарий работы:
#
# 1. Создаёт папки:
#    - C:\IntelPack
#    - C:\IntelPack\temp
#
# 2. Скачивает в temp следующие установщики Intel:
#    - Chipset
#    - Serial IO
#    - HID Event Filter
#    - DTT
#    - MEI
#
# 3. Для каждого .exe:
#    - создаёт отдельную папку по имени файла
#    - запускает распаковку через /extract:... /quiet
#
# 4. После попытки распаковки:
#    - удаляет все .exe внутри C:\IntelPack
#
# 5. Создаёт ZIP-архив со всем содержимым папки C:\IntelPack
#
# Особенности:
#
# - При ошибке PowerShell-команд скрипт останавливается
# - Ошибки распаковки отдельных драйверов перехватываются отдельно
# - Скрипт не проверяет цифровую подпись файлов
# - Скрипт не проверяет, поддерживает ли конкретный .exe ключ /extract
# - Некоторые драйверы могут не распаковаться таким способом
# ======================================================================

# ----------------------------------------------------------------------
# Если в PowerShell происходит ошибка, выполнение скрипта останавливается
# ----------------------------------------------------------------------
$ErrorActionPreference = "Stop"

# ----------------------------------------------------------------------
# Базовая папка для всего набора драйверов
# ----------------------------------------------------------------------
$base = "C:\IntelPack"

# ----------------------------------------------------------------------
# Временная папка для скачанных установщиков
# ----------------------------------------------------------------------
$temp = "$base\temp"

# ----------------------------------------------------------------------
# Создаём:
# - основную папку
# - временную папку
#
# -Force позволяет не выдавать ошибку, если папки уже существуют
# Out-Null скрывает служебный вывод команды
# ----------------------------------------------------------------------
New-Item -ItemType Directory -Force -Path $base, $temp | Out-Null

# ----------------------------------------------------------------------
# Список прямых ссылок на Intel-драйверы, которые нужно скачать
# ----------------------------------------------------------------------
$drivers = @(
    "https://downloadmirror.intel.com/19347/eng/SetupChipset.exe",
    "https://downloadmirror.intel.com/19351/eng/SetupSerialIO.exe",
    "https://downloadmirror.intel.com/19350/eng/SetupHIDEventFilter.exe",
    "https://downloadmirror.intel.com/19695/eng/DTTSetup.exe",
    "https://downloadmirror.intel.com/682431/eng/MEISetup.exe"
)

# ----------------------------------------------------------------------
# Сообщаем пользователю, что начинается скачивание
# ----------------------------------------------------------------------
Write-Host "Downloading drivers..."

# ----------------------------------------------------------------------
# Проходим по каждой ссылке в массиве $drivers
# ----------------------------------------------------------------------
foreach ($url in $drivers) {

    # Получаем имя файла из URL и формируем путь сохранения в temp
    $file = Join-Path $temp ([System.IO.Path]::GetFileName($url))

    # Скачиваем файл по URL в нужный путь
    Invoke-WebRequest -Uri $url -OutFile $file
}

# ----------------------------------------------------------------------
# Сообщаем, что начинается распаковка скачанных .exe
# ----------------------------------------------------------------------
Write-Host "Extracting..."

# ----------------------------------------------------------------------
# Ищем все .exe-файлы в папке temp и пытаемся распаковать каждый
# ----------------------------------------------------------------------
Get-ChildItem -Path $temp -Filter *.exe | ForEach-Object {

    # Создаём папку назначения по имени файла без расширения
    # Например:
    # SetupChipset.exe -> C:\IntelPack\SetupChipset
    $dest = Join-Path $base $_.BaseName

    # Создаём папку для распаковки
    New-Item -ItemType Directory -Force -Path $dest | Out-Null

    try {
        # --------------------------------------------------------------
        # Пытаемся запустить установщик с параметрами:
        # /extract:$dest  -> распаковать в указанную папку
        # /quiet          -> тихий режим
        #
        # -Wait ждёт завершения процесса
        # --------------------------------------------------------------
        Start-Process -FilePath $_.FullName -ArgumentList "/extract:$dest /quiet" -Wait
    }
    catch {
        # Если конкретный .exe не поддержал распаковку или произошла ошибка
        Write-Host "Extract failed: $($_.Name)"
    }
}

# ----------------------------------------------------------------------
# Сообщаем, что начинается очистка
# ----------------------------------------------------------------------
Write-Host "Cleaning..."

# ----------------------------------------------------------------------
# Удаляем все .exe-файлы внутри C:\IntelPack и его подпапок
#
# Это убирает:
# - скачанные установщики из temp
# - любые exe, которые могли остаться после распаковки
# ----------------------------------------------------------------------
Get-ChildItem -Path $base -Recurse -Include *.exe | Remove-Item -Force -ErrorAction SilentlyContinue

# ----------------------------------------------------------------------
# Сообщаем, где находится подготовленная папка с драйверами
# ----------------------------------------------------------------------
Write-Host "Done: $base"

# ----------------------------------------------------------------------
# Сообщаем, что начинается создание ZIP-архива
# ----------------------------------------------------------------------
Write-Host "Creating ZIP..."

# ----------------------------------------------------------------------
# Упаковываем всё содержимое папки C:\IntelPack в архив
# C:\IntelPack_AlderLake.zip
#
# -Force перезапишет архив, если он уже существует
# ----------------------------------------------------------------------
Compress-Archive -Path "$base\*" -DestinationPath "C:\IntelPack_AlderLake.zip" -Force

# ----------------------------------------------------------------------
# Финальное сообщение об успешном создании архива
# ----------------------------------------------------------------------
Write-Host "ZIP created: C:\IntelPack_AlderLake.zip"