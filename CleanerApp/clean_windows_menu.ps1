# ========================================================================
# WINDOWS CLEANER (ПРОСТОЕ КОНСОЛЬНОЕ МЕНЮ ОЧИСТКИ WINDOWS)
# ========================================================================
#
# Что делает данный скрипт:
#
# Скрипт запускает простое текстовое меню в PowerShell и позволяет
# пользователю вручную выбрать один из вариантов очистки системы.
#
# Доступные действия:
#
# 1. Clean temp
#    Очищает временные файлы текущего пользователя (%TEMP%)
#
# 2. Clean Windows.old
#    Удаляет папку C:\Windows.old
#    Обычно остаётся после обновления Windows
#
# 3. Clean prefetch
#    Очищает содержимое папки Prefetch
#
# 4. Clean downloads
#    Полностью очищает папку Downloads текущего пользователя
#
# 5. Exit
#    Выход из программы
#
# Как работает:
#
# - Показывается меню
# - Пользователь вводит номер пункта
# - Выполняется выбранное действие
# - Затем ожидание клавиши через Pause
# - После этого меню открывается снова
# - Цикл продолжается до выбора пункта 5
#
# Особенности:
#
# - Ошибки скрываются через:
#   $ErrorActionPreference = "SilentlyContinue"
#
# - Если часть файлов занята системой или программами,
#   скрипт просто пропустит их без остановки.
#
# Важные предупреждения:
#
# - Пункт Downloads удаляет файлы без корзины
# - Пункт Windows.old может потребовать запуск от администратора
# - Prefetch лучше очищать только при необходимости
# ========================================================================

# ------------------------------------------------------------------------
# Подавление вывода ошибок PowerShell
# Скрипт не будет прерываться из-за мелких ошибок удаления
# ------------------------------------------------------------------------
$ErrorActionPreference = "SilentlyContinue"

# ------------------------------------------------------------------------
# Функция отображения меню
# Каждый раз очищает экран и выводит список действий
# ------------------------------------------------------------------------
function Show-Menu {

    # Очистка экрана консоли
    Clear-Host

    # Заголовок меню
    Write-Host "=== Windows Cleaner ==="

    # Пункты меню
    Write-Host "1. Clean temp"
    Write-Host "2. Clean Windows.old"
    Write-Host "3. Clean prefetch"
    Write-Host "4. Clean downloads"
    Write-Host "5. Exit"
}

# ------------------------------------------------------------------------
# Основной цикл программы
# Работает до тех пор, пока пользователь не выберет пункт 5
# ------------------------------------------------------------------------
do {

    # Показываем меню
    Show-Menu

    # Просим пользователя ввести номер действия
    $choice = Read-Host "Enter option number"

    # --------------------------------------------------------------------
    # Обрабатываем выбор пользователя через switch
    # --------------------------------------------------------------------
    switch ($choice) {

        # ---------------------------------------------------------------
        # Пункт 1 — очистка временных файлов пользователя
        # ---------------------------------------------------------------
        "1" {
            Write-Host "Cleaning temp..."

            # Удаляем всё содержимое папки TEMP
            Remove-Item "$env:TEMP\*" -Recurse -Force -ErrorAction SilentlyContinue
        }

        # ---------------------------------------------------------------
        # Пункт 2 — удаление Windows.old
        # ---------------------------------------------------------------
        "2" {
            Write-Host "Cleaning Windows.old..."

            # Удаляем папку Windows.old
            Remove-Item "C:\Windows.old" -Recurse -Force -ErrorAction SilentlyContinue
        }

        # ---------------------------------------------------------------
        # Пункт 3 — очистка Prefetch
        # ---------------------------------------------------------------
        "3" {
            Write-Host "Cleaning prefetch..."

            # Удаляем содержимое папки Prefetch
            Remove-Item "C:\Windows\Prefetch\*" -Recurse -Force -ErrorAction SilentlyContinue
        }

        # ---------------------------------------------------------------
        # Пункт 4 — очистка Downloads
        # ---------------------------------------------------------------
        "4" {
            Write-Host "Cleaning downloads..."

            # Удаляем всё содержимое папки Загрузки пользователя
            Remove-Item "$env:USERPROFILE\Downloads\*" -Recurse -Force -ErrorAction SilentlyContinue
        }

        # ---------------------------------------------------------------
        # Пункт 5 — выход из программы
        # ---------------------------------------------------------------
        "5" {
            break
        }

        # ---------------------------------------------------------------
        # Если введён неверный номер
        # ---------------------------------------------------------------
        default {
            Write-Host "Invalid option"
        }
    }

    # --------------------------------------------------------------------
    # Пауза после выполнения действия
    # Ожидание нажатия клавиши пользователем
    # --------------------------------------------------------------------
    Pause

# Цикл продолжается пока не выбран пункт 5
} while ($choice -ne "5")