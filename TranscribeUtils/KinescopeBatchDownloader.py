# ======================================================================
# KINESCOPE BATCH DOWNLOADER (JSON -> MP4 + MP3)
# ======================================================================
#
# Что делает данный Python-скрипт:
#
# Скрипт пакетно обрабатывает JSON-файлы логов Kinescope Player
# (например kinescope_player_1759332958625.json),
# извлекает из них прямые ссылки на HLS поток (master.m3u8),
# затем автоматически скачивает:
#
# 🎞 Видео в формате MP4
# 🎧 Аудио в формате MP3
#
# ----------------------------------------------------------------------
# Основной сценарий работы:
#
# 1. Пользователь вводит:
#    - папку с JSON файлами
#    - папку для MP3
#    - папку для MP4
#
# 2. Скрипт ищет все *.json файлы
#
# 3. Для каждого JSON:
#    - читает содержимое
#    - ищет ссылку HLS master.m3u8
#
# 4. Если ссылка найдена:
#    - скачивает MP4 через yt-dlp
#
# 5. После скачивания:
#    - проверяет через ffprobe наличие аудиодорожки
#
# 6. Если аудио есть:
#    - извлекает MP3 через yt-dlp + ffmpeg
#
# 7. Показывает прогресс обработки через tqdm
#
# 8. В конце выводит сообщение об окончании работы
#
# ----------------------------------------------------------------------
# Что требуется:
#
# - Python 3.10+
# - pip install tqdm
# - yt-dlp должен быть установлен
# - ffmpeg / ffprobe должны существовать по указанному пути
#
# ----------------------------------------------------------------------
# Используется для массового скачивания уроков / видео из JSON логов
# Kinescope player.
# ======================================================================


# ----------------------------------------------------------------------
# Импорт стандартных библиотек
# ----------------------------------------------------------------------

import json                 # Работа с JSON файлами
import subprocess           # Запуск внешних программ (yt-dlp, ffprobe)
from pathlib import Path    # Удобная работа с путями


# ----------------------------------------------------------------------
# Импорт сторонней библиотеки tqdm
# Для красивого progress bar
# ----------------------------------------------------------------------

from tqdm import tqdm


# ----------------------------------------------------------------------
# Убирает префикс kinescope_player_ из имени файла
#
# Пример:
# kinescope_player_1759332958625.json
# ->
# 1759332958625
# ----------------------------------------------------------------------

def clean_name(filename: str) -> str:
    """Убирает префикс 'kinescope_player_' из имени файла."""
    return filename.removeprefix("kinescope_player_")


# ----------------------------------------------------------------------
# Пытается извлечь ссылку HLS master.m3u8 из JSON структуры
#
# Возможные варианты расположения:
#
# data["options"]["playlist"][0]["sources"]["hls"]["src"]
#
# или:
#
# data["rawOptions"]["playlist"][0]["sources"]["hls"]["src"]
# ----------------------------------------------------------------------

def extract_kinescope_url(data: dict) -> str | None:
    """Извлекает ссылку HLS из JSON."""

    try:
        return data["options"]["playlist"][0]["sources"]["hls"]["src"]

    except Exception:
        try:
            return data["rawOptions"]["playlist"][0]["sources"]["hls"]["src"]

        except Exception:
            return None


# ----------------------------------------------------------------------
# Проверяет есть ли аудиопоток в скачанном видео
#
# Используется ffprobe.exe
#
# Возвращает:
# True  - если аудио найдено
# False - если аудио отсутствует
# ----------------------------------------------------------------------

def has_audio(video_path: Path, ffmpeg_path: str) -> bool:
    """Проверка наличия аудиодорожки."""

    # Формируем путь к ffprobe.exe
    ffprobe_exe = Path(ffmpeg_path) / "ffprobe.exe"

    # Если ffprobe не найден — ошибка
    if not ffprobe_exe.exists():
        raise FileNotFoundError(
            f"⚠️ ffprobe.exe не найден по пути: {ffprobe_exe}"
        )

    # Запускаем ffprobe
    result = subprocess.run(
        [
            str(ffprobe_exe),
            "-v", "error",
            "-select_streams", "a:0",
            "-show_entries", "stream=codec_type",
            "-of", "csv=p=0",
            str(video_path)
        ],
        text=True,
        capture_output=True
    )

    # Если в выводе есть audio — значит аудио найдено
    return "audio" in result.stdout.lower()


# ----------------------------------------------------------------------
# Главная функция программы
# ----------------------------------------------------------------------

def main():

    print("🎬 Kinescope Batch Downloader with Audio Check")

    # --------------------------------------------------------------
    # Получаем пути от пользователя
    # --------------------------------------------------------------

    json_dir = Path(
        input("📁 Введите путь к папке с JSON файлами: ").strip('"')
    )

    mp3_dir = Path(
        input("🎧 Введите путь для сохранения MP3: ").strip('"')
    )

    mp4_dir = Path(
        input("🎞 Введите путь для сохранения MP4: ").strip('"')
    )

    # --------------------------------------------------------------
    # Проверяем наличие папки с JSON
    # --------------------------------------------------------------

    if not json_dir.exists():
        print(f"❌ Папка {json_dir} не найдена.")
        return

    # --------------------------------------------------------------
    # Создаём папки назначения
    # --------------------------------------------------------------

    mp3_dir.mkdir(parents=True, exist_ok=True)
    mp4_dir.mkdir(parents=True, exist_ok=True)

    # --------------------------------------------------------------
    # Ищем все json файлы
    # --------------------------------------------------------------

    json_files = list(json_dir.glob("*.json"))

    if not json_files:
        print("⚠️ В папке нет JSON файлов.")
        return

    print(f"📄 Найдено {len(json_files)} JSON файлов.\n")

    # --------------------------------------------------------------
    # Путь к ffmpeg / ffprobe
    # Указать свой путь при необходимости
    # --------------------------------------------------------------

    ffmpeg_path = r"D:\DEV\lib\ffmpeg-8.0-essentials_build\bin"

    # --------------------------------------------------------------
    # Обрабатываем каждый JSON файл
    # --------------------------------------------------------------

    for json_file in tqdm(
        json_files,
        desc="📥 Обработка файлов",
        ncols=90,
        colour="cyan"
    ):

        try:
            # ------------------------------------------------------
            # Загружаем JSON
            # ------------------------------------------------------

            with open(json_file, "r", encoding="utf-8") as f:
                data = json.load(f)

            # ------------------------------------------------------
            # Ищем ссылку на поток
            # ------------------------------------------------------

            url = extract_kinescope_url(data)

            if not url:
                tqdm.write(
                    f"⚠️ {json_file.name}: "
                    f"не удалось найти ссылку HLS. Пропуск."
                )
                continue

            # ------------------------------------------------------
            # Формируем имя файлов
            # ------------------------------------------------------

            base_name = clean_name(json_file.stem)

            # ======================================================
            # СКАЧИВАЕМ MP4
            # ======================================================

            mp4_out = mp4_dir / f"{base_name}.mp4"

            tqdm.write(f"\n🎞 Скачиваем видео → {mp4_out.name}")

            result = subprocess.run(
                [
                    "yt-dlp",
                    "--merge-output-format", "mp4",
                    "--ffmpeg-location", ffmpeg_path,
                    "-o", str(mp4_out),
                    url
                ],
                text=True,
                capture_output=True
            )

            # Проверяем результат скачивания
            if result.returncode != 0:
                tqdm.write(
                    f"❌ Ошибка видео: "
                    f"{result.stderr.strip()[:200]}"
                )

            elif not mp4_out.exists():
                tqdm.write(f"⚠️ Видео не создано: {mp4_out}")

            else:
                tqdm.write(f"✅ Видео сохранено: {mp4_out}")

            # ======================================================
            # ПРОВЕРЯЕМ НАЛИЧИЕ АУДИО
            # ======================================================

            if not has_audio(mp4_out, ffmpeg_path):
                tqdm.write(
                    f"🔇 {mp4_out.name}: "
                    f"аудиопоток отсутствует, MP3 не создаётся.\n"
                )
                continue

            # ======================================================
            # СКАЧИВАЕМ MP3
            # ======================================================

            mp3_out = mp3_dir / f"{base_name}.mp3"

            tqdm.write(f"🎧 Извлекаем аудио → {mp3_out.name}")

            result = subprocess.run(
                [
                    "yt-dlp",
                    "-f", "bestaudio[ext=m4a]/bestaudio/best",
                    "-x",
                    "--audio-format", "mp3",
                    "--ffmpeg-location", ffmpeg_path,
                    "-o", str(mp3_out),
                    url
                ],
                text=True,
                capture_output=True
            )

            # Проверяем результат
            if result.returncode != 0:
                tqdm.write(
                    f"❌ Ошибка аудио: "
                    f"{result.stderr.strip()[:300]}"
                )

            elif not mp3_out.exists():
                tqdm.write(f"⚠️ Аудио не создано: {mp3_out}")

            else:
                tqdm.write(f"✅ Аудио сохранено: {mp3_out}")

        # ----------------------------------------------------------
        # Если ошибка на конкретном файле — выводим и продолжаем
        # ----------------------------------------------------------

        except Exception as e:
            tqdm.write(
                f"❌ Ошибка при обработке {json_file.name}: {e}"
            )

    # --------------------------------------------------------------
    # Финал работы
    # --------------------------------------------------------------

    print("\n🎉 Обработка завершена!")


# ----------------------------------------------------------------------
# Точка входа в программу
# ----------------------------------------------------------------------

if __name__ == "__main__":
    main()