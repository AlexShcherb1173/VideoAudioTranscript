"""merge_mp3_auto.py — Скрипт для объединения нескольких MP3 файлов в один с помощью FFmpeg.

Функционал:
- Запрашивает у пользователя путь к папке с MP3 файлами.
- Запрашивает путь для временного файла со списком треков (если указана папка, создаётся tracks.txt внутри).
- Запрашивает имя итогового MP3 файла.
- Создаёт список MP3 файлов для FFmpeg.
- Объединяет их в один аудиофайл с прогрессбаром.
- После успешного объединения удаляет временный список треков.

Требования:
- Установленный FFmpeg (в PATH).
- Модуль tqdm (`pip install tqdm`)."""

# ----------------------------------------------------------------------
# Импорт стандартных и внешних модулей
# ----------------------------------------------------------------------

import subprocess              # Для запуска FFmpeg как внешнего процесса
from pathlib import Path       # Для удобной и безопасной работы с путями
from tqdm import tqdm          # Для отображения progress bar в консоли
import os                      # Импортирован в исходном коде, хотя в логике не используется


def prepare_list_file(mp3_dir: Path, list_path: Path) -> None:
    """Создаёт временный файл со списком MP3 для объединения через FFmpeg.
    :param mp3_dir: Папка, где находятся MP3 файлы.
    :param list_path: Путь к файлу со списком треков (например, data/tracks.txt)."""

    # ------------------------------------------------------------------
    # Ищем все mp3-файлы в указанной папке и сортируем их
    # Это важно, чтобы объединение шло в предсказуемом порядке
    # ------------------------------------------------------------------
    mp3_files = sorted(mp3_dir.glob("*.mp3"))

    # Если mp3-файлы не найдены — сообщаем пользователю и вызываем ошибку
    if not mp3_files:
        print("⚠️ В указанной папке нет MP3 файлов.")
        raise FileNotFoundError("Нет MP3 файлов для объединения")

    # Выводим список найденных файлов
    print(f"📄 Найдено {len(mp3_files)} MP3 файлов:\n")
    for i, f in enumerate(mp3_files, 1):
        print(f"  {i:02}. {f.name}")

    # ------------------------------------------------------------------
    # Создаём текстовый файл со списком треков для FFmpeg concat demuxer
    # Формат строки:
    # file 'полный_путь_к_файлу'
    # ------------------------------------------------------------------
    with list_path.open("w", encoding="utf-8") as f:
        for mp3 in mp3_files:
            f.write(f"file '{mp3.resolve()}'\n")

    # Сообщаем, куда был сохранён временный список
    print(f"\n🧾 Список треков сохранён: {list_path}")


def merge_mp3(list_path: Path, output_path: Path) -> None:
    """ Объединяет MP3 файлы в один при помощи FFmpeg.
    :param list_path: Путь к файлу со списком MP3 (tracks.txt).
    :param output_path: Путь к итоговому MP3 файлу."""

    # Сообщаем пользователю, что начинается объединение
    print(f"\n🔄 Объединяем треки в {output_path} ...")

    # ------------------------------------------------------------------
    # Команда FFmpeg для объединения файлов:
    # -f concat   -> использовать режим concat
    # -safe 0     -> разрешить абсолютные пути
    # -i          -> входной файл со списком
    # -c copy     -> копировать потоки без перекодирования
    # ------------------------------------------------------------------
    command = [
        "ffmpeg",
        "-f", "concat",
        "-safe", "0",
        "-i", str(list_path),
        "-c", "copy",
        str(output_path)
    ]

    # ------------------------------------------------------------------
    # Запускаем FFmpeg как процесс
    # stdout и stderr читаются как текст
    # stderr используется, потому что FFmpeg обычно пишет ход работы туда
    # ------------------------------------------------------------------
    process = subprocess.Popen(command, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)

    # ------------------------------------------------------------------
    # Строим progress bar на основе построчного чтения stderr FFmpeg
    # tqdm здесь показывает активность процесса, а не точный процент длины
    # ------------------------------------------------------------------
    for _ in tqdm(iter(process.stderr.readline, ""), desc="🎶 Слияние", colour="magenta", ncols=90):
        if process.poll() is not None:
            break

    # Ждём полного завершения процесса
    process.wait()

    # Если FFmpeg завершился без ошибки
    if process.returncode == 0:
        print(f"\n✅ Готово! Итоговый MP3 сохранён как: {output_path}")

        # --------------------------------------------------------------
        # После успешного объединения удаляем временный tracks.txt
        # --------------------------------------------------------------
        try:
            list_path.unlink(missing_ok=True)
            print(f"🧹 Временный файл {list_path.name} удалён.")
        except Exception as e:
            print(f"⚠️ Не удалось удалить {list_path}: {e}")
    else:
        # Если FFmpeg завершился с ошибкой — выводим код возврата
        print(f"\n❌ Ошибка при объединении файлов. Код возврата: {process.returncode}")


def main() -> None:
    """Основная точка входа в программу."""

    # Заголовок программы
    print("🎧 FFmpeg MP3 Merger (Auto + Progress Bar + Smart Path + Cleanup)\n")

    # ─────────────── Ввод пользователя ───────────────
    # Пользователь вводит:
    # 1. Папку с mp3 файлами
    # 2. Путь к списку треков или папку, где он будет создан
    # 3. Имя итогового mp3 файла
    mp3_dir = Path(input("📁 Введите путь к папке с MP3: ").strip('"'))
    list_path = Path(input("📄 Введите путь и имя списка (например data или data/tracks.txt): ").strip('"'))
    output_name = input("🎵 Введите имя итогового MP3 файла (например merged.mp3): ").strip()

    # ─────────────── Проверки ───────────────
    # Проверяем, существует ли папка с mp3
    if not mp3_dir.exists():
        print(f"❌ Папка {mp3_dir} не найдена.")
        return

    # ------------------------------------------------------------------
    # Если пользователь ввёл только папку или путь без расширения,
    # автоматически создаём tracks.txt внутри этой папки
    # ------------------------------------------------------------------
    if list_path.is_dir() or list_path.suffix == "":
        list_path = list_path / "tracks.txt"

    # Создаём папку для списка, если её ещё нет
    list_path.parent.mkdir(parents=True, exist_ok=True)

    # ------------------------------------------------------------------
    # Если пользователь не указал расширение .mp3 для итогового файла,
    # добавляем его автоматически
    # ------------------------------------------------------------------
    output_path = Path(output_name)
    if not output_path.suffix:
        output_path = output_path.with_suffix(".mp3")

    # ─────────────── Обработка ───────────────
    # Генерируем tracks.txt и запускаем объединение
    try:
        prepare_list_file(mp3_dir, list_path)
        merge_mp3(list_path, output_path)
    except Exception as e:
        print(f"\n❌ Ошибка: {e}")


# ----------------------------------------------------------------------
# Точка входа: код внутри блока выполнится только при прямом запуске файла
# ----------------------------------------------------------------------
if __name__ == "__main__":
    main()

