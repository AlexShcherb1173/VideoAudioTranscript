# Что делает данный блок:
#
# 1. Получает аргументы командной строки:
#    - путь к MP3-файлу
#    - путь для сохранения TXT-файла
#    - имя модели Whisper (tiny/base/small/medium/large)
#
# 2. Загружает модель Whisper.
#
# 3. Если кэш модели повреждён (ошибка SHA256 checksum),
#    автоматически удаляет битый файл модели из кэша и
#    повторно скачивает модель.
#
# 4. Загружает аудио:
#    - декодирует файл
#    - подготавливает длину сигнала
#    - строит mel-спектрограмму
#
# 5. Определяет язык речи в аудио.
#
# 6. Запускает транскрибацию файла через Whisper.
#    В текущем коде распознавание принудительно задано:
#    language="ru"
#    (то есть результат ожидается на русском языке)
#
# 7. Получает сегменты распознавания, объединяет текст.
#
# 8. Создаёт папку назначения при необходимости.
#
# 9. Сохраняет итоговый текст в UTF-8 файл.
#
# 10. Показывает прогресс обработки через tqdm.
#
# Используется внутри PowerShell как here-string:
# $pyCode = @" ... "@
# Затем обычно временно сохраняется в .py и запускается Python.
