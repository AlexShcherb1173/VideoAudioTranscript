$pyCode = @"
# ---------------------------------------------------------------
# Импорт стандартных модулей Python
# ---------------------------------------------------------------

import sys                     # Работа с аргументами командной строки
from pathlib import Path       # Удобная работа с путями файлов и папок

# ---------------------------------------------------------------
# Импорт внешних библиотек
# ---------------------------------------------------------------

import whisper                 # OpenAI Whisper для распознавания речи
from tqdm import tqdm          # Красивый прогресс-бар в консоли

# ---------------------------------------------------------------
# Получаем аргументы запуска скрипта:
# argv[1] = путь к mp3
# argv[2] = путь к txt результату
# argv[3] = имя модели whisper
# ---------------------------------------------------------------

mp3_path = Path(sys.argv[1])
out_txt = Path(sys.argv[2])
model_name = sys.argv[3]

# ---------------------------------------------------------------
# Функция загрузки модели Whisper с защитой от битого кэша
# ---------------------------------------------------------------

def load_model_with_retry(name: str):

    # Пытаемся загрузить модель штатно
    try:
        return whisper.load_model(name)

    # Если произошла RuntimeError ошибка
    except RuntimeError as e:

        msg = str(e)

        # -------------------------------------------------------
        # Whisper иногда падает, если скачанная модель повреждена
        # (ошибка контрольной суммы SHA256)
        # -------------------------------------------------------

        if "SHA256 checksum does not not match" in msg or "SHA256 checksum does not match" in msg:

            # Папка кэша моделей Whisper в профиле пользователя
            cache_dir = Path.home() / ".cache" / "whisper"

            # ---------------------------------------------------
            # Соответствие имени модели и имени файла в кэше
            # ---------------------------------------------------

            broken_files = {
                "tiny": "tiny.pt",
                "base": "base.pt",
                "small": "small.pt",
                "medium": "medium.pt",
                "large": "large-v2.pt",
            }

            # Полный путь к повреждённому файлу модели
            broken_file = cache_dir / broken_files[name]

            # Если файл реально существует — удаляем
            if broken_file.exists():
                print(f"Corrupted model cache detected. Removing: {broken_file}")
                broken_file.unlink()

            # Повторная попытка скачивания модели
            print("Retrying model download...")
            return whisper.load_model(name)

        # Если ошибка другая — пробрасываем дальше
        raise


# ---------------------------------------------------------------
# Сообщаем пользователю какая модель загружается
# ---------------------------------------------------------------

print(f"Loading Whisper model: {model_name}")

# Загружаем модель
model = load_model_with_retry(model_name)

# ---------------------------------------------------------------
# Подготовка аудио
# ---------------------------------------------------------------

print("Preparing audio...")

# Загружаем аудиофайл в массив данных
audio = whisper.load_audio(str(mp3_path))

# Обрезаем или дополняем до нужной длины
audio = whisper.pad_or_trim(audio)

# ---------------------------------------------------------------
# Строим mel-спектрограмму и переносим на устройство модели
# (CPU / GPU)
# ---------------------------------------------------------------

mel = whisper.log_mel_spectrogram(audio).to(model.device)

# ---------------------------------------------------------------
# Автоматическое определение языка речи
# ---------------------------------------------------------------

print("Detecting language...")

_, probs = model.detect_language(mel)

# Берём язык с максимальной вероятностью
lang = max(probs, key=probs.get)

print(f"Detected language: {lang}")

print("")
print("Starting transcription...")
print("")

# ---------------------------------------------------------------
# Основная транскрибация
#
# ВАЖНО:
# несмотря на автоопределение языка выше,
# здесь язык жёстко задан как русский.
# ---------------------------------------------------------------

result = model.transcribe(str(mp3_path), language="ru")

# ---------------------------------------------------------------
# Получаем список сегментов текста:
# каждый сегмент содержит start/end/text
# ---------------------------------------------------------------

segments = result["segments"]

# Список для накопления текста
text_parts = []

print("Processing segments:")

# ---------------------------------------------------------------
# Обрабатываем каждый сегмент с прогресс-баром tqdm
# ---------------------------------------------------------------

for seg in tqdm(segments, desc="Transcribing", unit="segment"):

    # Время начала сегмента
    start = seg["start"]

    # Время окончания сегмента
    end = seg["end"]

    # Текст сегмента
    txt = seg["text"]

    # Добавляем текст в общий список
    text_parts.append(txt)

# ---------------------------------------------------------------
# Склеиваем весь текст в одну строку
# ---------------------------------------------------------------

text = "".join(text_parts)

# ---------------------------------------------------------------
# Создаём папку назначения если её нет
# ---------------------------------------------------------------

out_txt.parent.mkdir(parents=True, exist_ok=True)

# ---------------------------------------------------------------
# Сохраняем текстовый файл UTF-8
# ---------------------------------------------------------------

out_txt.write_text(text, encoding="utf-8")

print("")
print(f"Saved text to: {out_txt}")
"@